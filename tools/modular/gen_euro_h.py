#!/usr/bin/env python3
"""Writes native_ui/NjoEuro.h (module table of the Eurorack rack) from tools/modular/euro_modules.py.  python3 tools/modular/gen_euro_h.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from euro_modules import *
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
q = lambda s: '"%s"' % s
def arr(l, n): return '{ ' + ', '.join(q(x) for x in (list(l) + [''] * n)[:n]) + ' }'
o = ['// GENERATED by tools/modular/gen_euro_h.py from tools/modular/euro_modules.py - do not edit', '#pragma once', 'namespace njo { namespace euro {',
     'constexpr int kSlots = %d, kBase = %d, kStride = %d, kTypes = %d;' % (NSLOT, BASE, STRIDE, NTYPE),
     'struct Mod { const char* name; const char* knobs[8]; int nModes; const char* modes[8]; const char* ins[4]; const char* outs[2]; };',
     'inline const Mod* mods() { static const Mod t[kTypes] = {']
for n, kb, md, ins, outs in MODS:
    o.append('    { %s, %s, %d, %s, %s, %s },' % (q(n), arr(kb, 8), len(md), arr(md, 8), arr(ins, 4), arr(outs, 2)))
o += ['}; return t; }', '}}']
open(os.path.join(root, 'native_ui', 'NjoEuro.h'), 'w').write('\n'.join(o) + '\n')
print('ok')
