"""Shared helpers of the source generators (build_gr.py, build_ad.py): block insertion into the Cmajor patch and the C++ id header."""
import os, re
import layout as L

def table(K, idx, n=16):
    v = [(0.0, 1.0)] * n
    out = [0.0] * n; hi = [1.0] * n
    for p in K: out[p[0]] = float(p[4]); hi[p[0]] = float(p[5])
    return ", ".join("%sf" % repr(x) for x in out), ", ".join("%sf" % repr(x) for x in hi)

def install(patch, after, tag, K, idfn, dstbase, dsp, voice, noteon, stepcall, setfn, parr, header, hdrname, ns, base, stride):
    s = open(patch).read()
    decl = "".join('    input event float param%d [[ name: "OSC %d %s", min: %s, max: %s, init: %s%s ]];\n' % (
        idfn(o, p[0]), o + 1, p[2], repr(float(p[4])), repr(float(p[5])), repr(float(p[6])), ", step: 1.0" if p[8] == "sel" else "")
        for o in range(L.OSC_COUNT) for p in K)
    hand = "".join("    event param%d (float v) { %s (%d, %d, v); }\n" % (idfn(o, p[0]), setfn, o, p[0]) for o in range(L.OSC_COUNT) for p in K)
    init = "".join("            %s.at (io * 16 + %d) = %sf;\n" % (parr, p[0], repr(float(p[6]))) for p in K)
    def block(t, body, anchor_re, indent="    "):
        nonlocal s
        a, z = "%s// %s-%s-BEGIN\n" % (indent, tag, t), "%s// %s-%s-END\n" % (indent, tag, t)
        s = re.sub(re.escape(a) + r".*?" + re.escape(z), "", s, flags=re.S)
        m = re.search(anchor_re, s, re.M)
        if not m: raise SystemExit("anchor not found: " + t)
        s = s[:m.start()] + a + body + z + s[m.start():]
    block("DSP", dsp, r"^    // PHYS-DSP-BEGIN")
    block("DECL", decl, r"^    input event float param1600 ")
    block("HAND", hand, r"^    event param1600 ")
    block("INIT", init, r"^            op\.at \(io \* 64 \+ 11\) = 3\.0f;\n", "            ")
    block("VOICE", voice, r"^        int     fdlW; ", "        ")
    s = re.sub(r'(name: "OSC \d Source", min: 0.0, max: )[2-8]\.0', r'\g<1>%d.0' % 9, s)
    def rep(old, new):
        nonlocal s
        if new in s: return
        assert s.count(old) == 1, (old[:80], s.count(old))
        s = s.replace(old, new)
    rep(after, after + noteon)
    if stepcall not in s:
        rep("\n                    // ----- filter envelope of the slot -----\n", "\n" + stepcall + "\n                    // ----- filter envelope of the slot -----\n")
    DMAX = L.N_DST_TOTAL - 1
    s = re.sub(r"(mmDstI\.at \(\d+\) = clamp \(int \(v \+ 0\.5f\), 0, )\d+\)", lambda m: m.group(1) + "%d)" % DMAX, s)
    s = re.sub(r'(Mod Slot \d+ Dest \(0-)\d+(, see Dest list\)", min: 0\.0, max: )\d+(\.0)', lambda m: m.group(1) + "%d" % DMAX + m.group(2) + "%d" % DMAX + m.group(3), s)
    open(patch, "w").write(s)
    hdr = os.path.join(os.path.dirname(os.path.abspath(patch)), "..", "native_ui", hdrname)
    with open(hdr, "w") as f:
        f.write("// generated by %s: parameter ids of the %s source\n#pragma once\n#include <string_view>\nnamespace njo::%s\n{\n" % (header, tag, ns))
        f.write("    constexpr int %s_BASE = %d, %s_STRIDE = %d;\n" % (ns.upper(), base, ns.upper(), stride))
        f.write("    inline int %sId (int o, int j) { return %s_BASE + %s_STRIDE * o + j; }\n" % (ns, ns.upper(), ns.upper()))
        f.write("    inline int key (const char* name)   // parameter index j of a key\n    {\n")
        for q in K: f.write('        if (std::string_view (name) == "%s") return %d;\n' % (q[1], q[0]))
        f.write("        return 0;\n    }\n}\n")
