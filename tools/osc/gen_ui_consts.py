#!/usr/bin/env python3
"""Writes tools/osc/ui_consts.js: the JS constants and spec rows of the 6-slot layout (from layout.py)."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import layout as L

ENGINES = [
 # name, group, Harmonics, Timbre, Morph
 ("VA + Filter",      "Classic", "Detune", "Cutoff", "Shape"),
 ("Phase Distortion", "Classic", "Detune", "Distortion", "Shape"),
 ("6-Op FM A",        "FM", "Patch", "Mod Level", "Env / Pitch"),
 ("6-Op FM B",        "FM", "Patch", "Mod Level", "Env / Pitch"),
 ("6-Op FM C",        "FM", "Patch", "Mod Level", "Env / Pitch"),
 ("Wave Terrain",     "Classic", "Terrain", "Radius", "Offset"),
 ("String Machine",   "Classic", "Chord", "Registration", "Waveform"),
 ("Chiptune",         "Classic", "Chord", "Pulse Width", "Arp / Env"),
 ("Virtual Analog",   "Classic", "Detune", "Pulse Width", "Saw Shape"),
 ("Waveshaper",       "Classic", "Waveform", "Fold", "Asymmetry"),
 ("FM",               "FM", "Ratio", "Mod Amount", "Feedback"),
 ("Formant / Grain",  "Classic", "Formant Ratio", "Formant Freq", "Formant Shape"),
 ("Additive",         "Classic", "Bumps", "Prominence", "Bump Shape"),
 ("Wavetable",        "Classic", "Bank", "Row", "Column"),
 ("Chords",           "Classic", "Chord", "Inversion", "Waveform"),
 ("Speech",           "Texture", "Species", "Phoneme", "Word / Vowel"),
 ("Swarm",            "Texture", "Pitch Random", "Density", "Overlap"),
 ("Filtered Noise",   "Texture", "Filter Type", "Clock Freq", "Resonance"),
 ("Particle",         "Texture", "Freq Random", "Density", "Filter"),
 ("String",           "Physical", "Inharmonicity", "Brightness", "Decay"),
 ("Modal",            "Physical", "Material", "Brightness", "Decay"),
 ("Bass Drum",        "Drums", "Attack", "Brightness", "Decay"),
 ("Snare Drum",       "Drums", "Mode Balance", "Excitation", "Decay"),
 ("Hi-Hat",           "Drums", "Metallic", "High-Pass", "Decay"),
]
groups, last = [], None
for i, e in enumerate(ENGINES):
    if e[1] != last: groups.append([i, e[1]]); last = e[1]

# the engines of the original Plaits are the ones from index 8 on; engine2 comes first in the list (index 0-7)
out = []
w = out.append
w("// ---- generated by tools/osc/gen_ui_consts.py from tools/osc/layout.py: do not edit by hand ----")
w("const OSC_N = %d, OSC_BASE = %d, OSC_STRIDE = %d, FM_BASE = %d, PM_BASE = %d, PD_BASE = %d;" % (L.OSC_COUNT, L.BASE, L.STRIDE, L.FM_BASE, L.PM_BASE, L.PD_BASE))
w("const OSC_K = %s;" % json.dumps(L.K))
w("const oscId = (o, k) => OSC_BASE + OSC_STRIDE * o + (typeof k === \"string\" ? OSC_K[k] : k);")
w("const fmId = (s, d) => FM_BASE + 6 * s + d;")
w("const pmId = (s, d) => PM_BASE + 6 * s + d;")
w("const pdId = (s, d) => PD_BASE + 6 * s + d;")
w("const OSC_SRC_TYPES = %s;" % json.dumps(L.SRC_TYPES))
w("const DIST_TYPES = %s;" % json.dumps(L.DIST_TYPES))
w("const OSC_OUTS = %s;" % json.dumps(L.OUTS))
w("const PLAITS_ENGINES = %s;" % json.dumps([e[0] for e in ENGINES]))
w("const PLAITS_GROUPS = %s;" % json.dumps(groups))
w("const PLAITS_PARAMS = %s;" % json.dumps([list(e[2:]) for e in ENGINES]))
dst = ["Off"] + L.MOD_DST_GLOBAL
for o in range(L.OSC_COUNT):
    dst += ["OSC %d %s" % (o + 1, n) for n in L.MOD_DST_OSC]
LET = "ABCDEF"
for kind in ("FM", "PM", "PD"):
    dst += ["%s %s > %s" % (kind, LET[a], LET[b]) for a in range(6) for b in range(6)]
dst += ["OSC %d %s" % (o + 1, n) for o in range(L.OSC_COUNT) for n in ("Wavefilter Pos", "Wavedistortion Pos")]
w("const MOD_DST = %s;" % json.dumps(dst))
w("const MOD_DST_GROUPS = %s;" % json.dumps([[0, ""], [1, "Global"]] + [[6 + 9 * o, "OSC %d" % (o + 1)] for o in range(L.OSC_COUNT)]
                                            + [[L.N_DST + 36 * i, "%s matrix (amount)" % n] for i, n in enumerate(("FM", "PM", "PD"))] + [[L.N_TBL_DST, "Tables"]]))
# mod ring targets: parameter number -> [matrix destination, knob travel per 1.0 amount]
t = {63: [1, 0.5], 29: [3, 0.5], 28: [4, 0.5], 190: [5, 0.5]}
for o in range(L.OSC_COUNT):
    b = 6 + 9 * o
    for key, j, sc in (("fine", 0, 0.5), ("level", 1, 1), ("pan", 2, 0.5), ("wpos", 3, 0.5), ("pharm", 3, 0.5), ("w1a", 4, 0.5), ("ptimb", 4, 0.5),
                        ("w2a", 5, 0.5), ("pmorph", 5, 0.5), ("fcut", 6, 0.41), ("fres", 7, 0.5), ("ddrv", 8, 0.5)):
        t[L.pid(o, L.K[key])] = [b + j, sc]
    t[L.pid(o, L.K["wfpos"])] = [L.N_TBL_DST + 2 * o, 0.5]
    t[L.pid(o, L.K["wdpos"])] = [L.N_TBL_DST + 2 * o + 1, 0.5]
for i, fn in enumerate((L.fm_id, L.pm_id, L.pd_id)):
    for a in range(6):
        for b in range(6):
            t[fn(a, b)] = [L.N_DST + 36 * i + 6 * a + b, 0.5]
w("const MOD_TARGET = %s;" % json.dumps(t))

def js_labels(p):
    k, key, label, short, lo, hi, init, unit, kind, labels = p
    if key in ("w1m", "w2m"): return "WARP_MODES", "null"
    if key == "ftype": return "OSC_FILTER_TYPES", "OSC_FILTER_GROUPS"
    if key == "pleng": return "PLAITS_ENGINES", "PLAITS_GROUPS"
    if labels: return json.dumps(labels), "null"
    return "null", "null"

rows = []
for o in range(L.OSC_COUNT):
    for p in L.PARAMS:
        k, key, label, short, lo, hi, init, unit, kind, labels = p
        lab, grp = js_labels(p)
        if kind == "sld" and unit == "": ukind = "sld"
        else: ukind = kind
        ini = 0.8 if (o == 0 and key == "level") else init
        rows.append("[%d, %s, %s, %s, %s, %s, %s, %s, 1, %s, %s]" % (L.pid(o, k), json.dumps("OSC %d %s" % (o + 1, label)), lo, hi, ini, json.dumps(unit), json.dumps(ukind), lab, json.dumps(short), grp))
for s in range(6):
    for d in range(6):
        for nm, fn in (("FM", L.fm_id), ("PM", L.pm_id), ("PD", L.pd_id)):
            rows.append("[%d, %s, 0, 100, 0, \"\", \"knb\", null, 1, \"%d→%d\", null]" % (fn(s, d), json.dumps("%s %d to %d" % (nm, s + 1, d + 1)), s + 1, d + 1))
w("const OSC_SPEC_ROWS = [\n    " + ",\n    ".join(rows) + "\n];")
open(os.path.join(os.path.dirname(__file__), "ui_consts.js"), "w").write("\n".join(out) + "\n")
print("ok", len(rows))
